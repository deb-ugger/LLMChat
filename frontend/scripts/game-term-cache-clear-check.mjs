import assert from "node:assert/strict";
import { build } from "esbuild";
import { fileURLToPath } from "node:url";

const storage = new Map();
globalThis.localStorage = { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, String(value)), removeItem: key => storage.delete(key) };
globalThis.window = { addEventListener() {}, removeEventListener() {}, dispatchEvent() {}, location: { hostname: "localhost" } };
Error.stackTraceLimit = 0;
const result = await build({ stdin: { contents: `export * from './gameTermMemory';export {resetGameTextScreening} from './gameTextProject';`, resolveDir: fileURLToPath(new URL("../src", import.meta.url)), loader: "ts" }, bundle: true, write: false, platform: "browser", format: "esm", external: ["fs", "path"], define: { "import.meta.env.VITE_API_BASE": '""' } });
const { clearGameTermMemory, prepareGameTerms, resetGameTextScreening } = await import("data:text/javascript;base64," + Buffer.from(result.outputFiles[0].text).toString("base64"));
const scope = "E:/Fixture/Game", source = "魔法追撃(全体)：炎";
const row = { id: "1", source, translation: "", selected: true, error: "", rpgTextKind: "skill" };
let requests = 0;
const makeTranslation = async () => { requests++; return "火焰追击(全体)"; };
const prepare = (references, reuseReferences = true, game = scope, target = "zh-CN") => prepareGameTerms([row], references, target, [], makeTranslation, new AbortController().signal, undefined, game, reuseReferences);
await prepare([row]);
assert.equal(requests, 1);
await prepare([row]);
assert.equal(requests, 1, "normal continuation reuses the new terminology cache");
await prepare([row], true, "E:/Fixture/OtherGame");
const otherBefore = [...storage].find(([key]) => key.includes("othergame"));
clearGameTermMemory("e:\\fixture\\game\\", "zh-CN");
assert.ok(![...storage.keys()].some(key => key.includes('"e:/fixture/game","zh-CN"')));
assert.deepEqual([...storage].find(([key]) => key.includes("othergame")), otherBefore);
const staleReference = { ...row, id: "old", selected: false, translation: "旧的火焰技能", translationTarget: "zh-CN" };
const before = requests;
const fresh = await prepare([row, staleReference], false);
assert.equal(requests, before + 1, "after clearing, old unselected translations do not recreate the deleted terminology cache");
assert.equal(fresh.terms.get(source), "火焰追击(全体)");
await prepare([row, staleReference], false);
assert.equal(requests, before + 1, "interrupt/resume can reuse terms already rebuilt after the clear");
const reset = resetGameTextScreening({ entries: [row], sourcePath: "fixture", translationPath: "", options: {}, workflow: { screened: true, freshTerms: true } });
assert.equal(reset.workflow.freshTerms, true, "re-screening does not cancel the request to rebuild terms");
clearGameTermMemory(scope, "zh-CN");
const configured = await prepareGameTerms([row], [row, staleReference], "zh-CN", [{ src: source, dst: "用户指定的译名" }], async () => { throw Error("manual glossary is not a cache"); }, new AbortController().signal, undefined, scope, false);
assert.equal(configured.terms.get(source), "用户指定的译名");
console.log("PASS scope-specific terminology deletion, rebuilding after clear, no stale-reference backfill, resumable new cache and preserved manual glossary");
